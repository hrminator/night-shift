"""Dump the exact model instruction text for every night turn type and arm.

Prints the full document to stdout and writes it to docs/instructions.md.
The text comes straight from the builders in app/runner.py, with the brief
and standing permission included verbatim. Resume sections are built from a
synthetic owner_answer event in a throwaway database using the canonical
hero answer ("Bergen: the venue can receive it" at 01:05); only the answer
event id (1) is synthetic, everything else is the live instruction text.
"""

from __future__ import annotations

import os
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

OUT_PATH = REPO / "docs" / "instructions.md"

CANONICAL_CHOICE = "Bergen: the venue can receive it"
CANONICAL_ANSWER_VT = "01:05"


def _build_sections() -> list[tuple[str, str]]:
    from app import runner
    from app.store import append_event, create_job

    job = create_job(job_id="instruction-dump", status="answered",
                     current_step="answered", virtual_time=CANONICAL_ANSWER_VT)
    answer = append_event(job["id"], CANONICAL_ANSWER_VT, "owner_answer",
                          {"choice": CANONICAL_CHOICE, "source": "owner"})
    return [
        ("read", runner.build_read_instructions()),
        ("reassess (supervision)",
         runner.build_reassess_instructions("supervision")),
        ("reassess (direct)", runner.build_reassess_instructions("direct")),
        ("resume (supervision)",
         runner.build_resume_instructions(job["id"], answer, "supervision")),
        ("resume (direct)",
         runner.build_resume_instructions(job["id"], answer, "direct")),
    ]


def generate_markdown() -> str:
    """Build the document in a throwaway DATA_DIR so output is deterministic."""
    with tempfile.TemporaryDirectory(prefix="night-shift-instructions-") as tmp:
        old = os.environ.get("DATA_DIR")
        os.environ["DATA_DIR"] = tmp
        try:
            sections = _build_sections()
        finally:
            if old is None:
                os.environ.pop("DATA_DIR", None)
            else:
                os.environ["DATA_DIR"] = old
    lines = [
        "# Night Shift model instructions",
        "",
        "Generated by `scripts/dump_instructions.py` from the builders in",
        "`app/runner.py`; do not edit by hand. The `read` turn is the same",
        "for both arms. Resume sections use a synthetic `owner_answer` event",
        f"with the canonical hero answer ({CANONICAL_CHOICE!r} at",
        f"{CANONICAL_ANSWER_VT}); only the answer event id is synthetic.",
        "",
    ]
    for heading, text in sections:
        lines += [f"## {heading}", "", text, ""]
    return "\n".join(lines)


def main() -> None:
    doc = generate_markdown()
    print(doc)
    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text(doc, encoding="utf-8")


if __name__ == "__main__":
    main()
